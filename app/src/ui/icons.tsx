export type IconName = keyof typeof BITMAPS | 'redo';

/** One rectangle per horizontal run of ink. */
function toPath(bitmap: string, mirror: boolean): string {
  const rows = bitmap.trim().split('\n');
  let d = '';
  rows.forEach((row, y) => {
    const line = mirror ? [...row].reverse().join('') : row;
    for (let x = 0; x < line.length; x++) {
      if (line[x] !== '#') continue;
      let end = x;
      while (line[end + 1] === '#') end++;
      d += `M${x} ${y}h${end - x + 1}v1h-${end - x + 1}z`;
      x = end;
    }
  });
  return d;
}

const PATHS: Record<IconName, string> = {
  ...(Object.fromEntries(Object.entries(BITMAPS).map(([name, bitmap]) => [name, toPath(bitmap, false)])) as Record<keyof typeof BITMAPS, string>),
  redo: toPath(BITMAPS.undo, true),
};

export function Icon({ name }: { name: IconName }) {
  return (
    <svg className="icon" viewBox="0 0 16 16" shapeRendering="crispEdges" aria-hidden="true">
      <path d={PATHS[name]} fill="currentColor" />
    </svg>
  );
}
